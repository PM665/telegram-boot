CREATE TABLE "bot_users" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    username VARCHAR(255) NOT NULL,
    locale VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (user_id)
);

CREATE TABLE "bot_chats" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL,
    bot_username VARCHAR(255),
    user_id BIGINT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (chat_id, bot_username)
);

CREATE TABLE "bot_user_permissions" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bot_username VARCHAR(255),
    access_type VARCHAR(255) NOT NULL,
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    code VARCHAR(255),
    UNIQUE (user_id, bot_username, access_type)
);

CREATE VIEW bot_users AS SELECT * FROM "bot_users";
CREATE VIEW bot_chats AS SELECT * FROM "bot_chats";
CREATE VIEW bot_user_permissions AS SELECT * FROM "bot_user_permissions";
